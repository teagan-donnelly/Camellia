package com.camellia.controller;

import com.camellia.ai.ClinicalAiService;
import com.camellia.ai.ClinicalAiService.Interpretation;
import com.camellia.search.SearchCriteria;
import com.camellia.search.SearchService;
import com.camellia.search.SearchService.SearchResult;
import com.camellia.web.ApiException;
import org.springframework.web.bind.annotation.*;

import java.util.Arrays;
import java.util.List;

@RestController
@RequestMapping("/api/search")
public class SearchController {

    private final SearchService search;
    private final ClinicalAiService ai;

    public SearchController(SearchService search, ClinicalAiService ai) {
        this.search = search;
        this.ai = ai;
    }

    /** Keyword + filter search. Multiple keywords must all match (AND). */
    @GetMapping
    public SearchResult search(@RequestParam(required = false) String q,
                               @RequestParam(required = false) String patientId,
                               @RequestParam(required = false) String orgId,
                               @RequestParam(required = false) String recordType,
                               @RequestParam(required = false) String concept,
                               @RequestParam(required = false) String from,
                               @RequestParam(required = false) String to) {
        List<String> keywords = q == null || q.isBlank() ? List.of() : Arrays.stream(q.trim().split("\\s+")).toList();
        SearchCriteria c = new SearchCriteria(q, keywords, csv(concept), csv(recordType), csv(orgId), patientId, from, to,
                false, false, false, false, 1, "ALL");
        if (!c.hasAnyFilter()) throw ApiException.badRequest("Provide a search term or at least one filter.");
        return search.search(c);
    }

    public record InterpretRequest(String query, String patientId) {}

    /** Gemini Capability 4: natural language → validated structured criteria (no SQL is generated by the model). */
    @PostMapping("/interpret")
    public Interpretation interpret(@RequestBody InterpretRequest req) {
        return ai.interpretSearch(req.query(), req.patientId() == null || req.patientId().isBlank() ? null : req.patientId());
    }

    /** Executes structured criteria (e.g. from /interpret) with approved, parameterized queries. */
    @PostMapping("/execute")
    public SearchResult execute(@RequestBody SearchCriteria criteria) {
        if (criteria == null || !criteria.hasAnyFilter()) throw ApiException.badRequest("Criteria must contain at least one filter.");
        return search.search(criteria);
    }

    private static List<String> csv(String s) {
        return s == null || s.isBlank() ? List.of() : Arrays.stream(s.split(",")).map(String::trim).filter(x -> !x.isEmpty()).toList();
    }
}
