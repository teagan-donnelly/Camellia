    public record RepositioningRequest(String patientId, String encounterId, LocalDateTime performedAt, String note) {}

    public MonitoringDetail documentRepositioning(DemoUser user, RepositioningRequest req) {
        auth.requirePermission(user, Permission.DOCUMENT_NURSING_INTERVENTIONS);
        if (req == null) throw ApiException.badRequest("Request body is required");
        Scoped sc = resolve(user, req.patientId(), req.encounterId());
        Session s = activeOrLatest(sc).orElse(null);
        LocalDateTime clock = s != null ? s.simClockAt() : LocalDateTime.now();
        LocalDateTime at = req.performedAt() != null ? req.performedAt() : clock;
        Encounter enc = sc.encounter();
        if (at.isBefore(enc.startTime()) || (enc.endTime() != null && at.isAfter(enc.endTime()))) {
            throw ApiException.badRequest("The repositioning time must fall within this hospital stay.");
        }
        if (at.isAfter(clock)) throw ApiException.badRequest("The repositioning time cannot be later than the current (simulated) time.");
        String note = req.note() == null ? null : req.note().trim();
        if (note != null && note.length() > 1000) throw ApiException.badRequest("note must be 1000 characters or fewer");
        repo.insertIntervention(new Intervention(SupportRepository.newId("INT"), enc.patientId(), enc.encounterId(),
                "REPOSITIONING", at, user.id(), user.name(), note == null || note.isEmpty() ? null : note, LocalDateTime.now()));
        repo.insertEvents(List.of(new ActivityEvent(SupportRepository.newId("EVT"), s == null ? null : s.sessionId(),
                enc.patientId(), enc.encounterId(), "REPOSITIONING_DOCUMENTED", at, null, null, "NURSE",
                "Repositioning documented by " + user.name() + (note == null || note.isEmpty() ? "" : " — " + note), user.name())));
        if (s != null) evaluate(s, user.name());
        support.logActivity("MONITORING", enc.encounterId(), enc.patientId(), "REPOSITIONING_DOCUMENTED",
                "Repositioning documented for " + at, user.name());
        return detail(user, enc.patientId(), enc.encounterId());
    }

    public record AlertStatusRequest(String status, String note) {}

    public Alert updateAlertStatus(DemoUser user, String alertId, AlertStatusRequest req) {
        auth.requirePermission(user, Permission.NURSING_MONITORING);
        Alert a = repo.alert(alertId).orElse(null);
        if (a == null || !auth.scope(user).allowsPatient(a.patientId())) throw AuthorizationService.denied(null);
        String target = req == null || req.status() == null ? "" : req.status().trim().toUpperCase(Locale.ROOT);
        boolean allowed = switch (a.status()) {
            case "OPEN" -> target.equals("ACKNOWLEDGED") || target.equals("RESOLVED");
            case "ACKNOWLEDGED" -> target.equals("RESOLVED");
            default -> false;
        };
        if (!allowed) throw ApiException.badRequest("Cannot change a " + a.status() + " monitoring alert to " + target + ".");
        if (req == null) throw ApiException.badRequest("status is required");
        String note = req.note() == null || req.note().isBlank() ? null : req.note().trim();
        repo.updateAlertStatus(alertId, target, LocalDateTime.now(), user.name(),
                target.equals("RESOLVED") ? (note != null ? note : "Reviewed and resolved by " + user.name()) : note);
        support.logActivity("MONITORING_ALERT", alertId, a.patientId(), "MONITORING_ALERT_" + target,
                a.alertType() + " → " + target, user.name());
        return repo.alert(alertId).orElseThrow();
    }

    /**
     * Applies the three nursing review rules at the session's simulated time. Rules never fire without an explicitly
     * configured care-plan interval; missing device data is reported as a device problem, never as patient inactivity.
     * At most one open (or acknowledged) alert per type and stay, so repeated evaluation cannot create duplicates.
     */
    void evaluate(Session s, String actor) {
        CarePlan plan = repo.plan(s.patientId(), s.encounterId()).orElse(null);
        List<Alert> alerts = repo.alerts(s.patientId(), s.encounterId());
        LocalDateTime now = s.simClockAt();
        int staleMinutes = plan != null && plan.staleDataMinutes() != null ? plan.staleDataMinutes() : props.getMonitoring().getStaleDataMinutes();
        boolean stale = !s.connected() || s.lastSyncAt() == null || Duration.between(s.lastSyncAt(), now).toMinutes() > staleMinutes;

        if (!s.active()) {
            resolveOpen(alerts, "DEVICE_CONNECTIVITY", now, actor, "Monitoring session stopped");
            return;
        }
        // C. Device connectivity
        if (stale) {
            String msg = !s.connected()
                    ? "Device connectivity review. The wristband is disconnected; no readings are being received. Absent readings are not evidence of patient inactivity."
                    : "Device connectivity review. No readings received for more than " + staleMinutes + " minutes. Absent readings are not evidence of patient inactivity.";
            open(alerts, s, "DEVICE_CONNECTIVITY", msg, "Last sync " + fmt(s.lastSyncAt()) + "; stale-data threshold " + staleMinutes + " min", now);
        } else {
            resolveOpen(alerts, "DEVICE_CONNECTIVITY", now, actor, "Readings resumed at " + fmt(s.lastSyncAt()));
        }
        // A. Mobility review — only with an explicit mobility plan, and never from stale or missing data.
        if (plan != null && plan.mobilityReviewMinutes() != null) {
            LocalDateTime lastWalk = lastWalkEnd(s);
            long since = Duration.between(lastWalk, now).toMinutes();
            if (!stale && since >= plan.mobilityReviewMinutes()) {
                boolean created = open(alerts, s, "MOBILITY_REVIEW",
                        "Mobility review suggested. No walking activity was detected during the configured interval. Verify the patient's status and review the mobility plan.",
                        "No walking detected since " + fmt(lastWalk) + " (" + since + " min; care-plan interval " + plan.mobilityReviewMinutes() + " min)", now);
                if (created) {
                    repo.insertEvents(List.of(event(s, "INACTIVITY_REVIEW", now, null, "SYSTEM",
                            "Mobility review triggered: no walking detected for " + since + " min", null)));
                }
            } else if (since < plan.mobilityReviewMinutes()) {
                resolveOpen(alerts, "MOBILITY_REVIEW", now, "System", "Walking detected at " + fmt(lastWalk));
            }
        }
        // B. Repositioning review — based only on confirmed nursing documentation, never on wrist movement.
        if (plan != null && plan.repositioningIntervalMinutes() != null) {
            LocalDateTime last = lastRepositioning(s);
            long since = Duration.between(last, now).toMinutes();
            if (since >= plan.repositioningIntervalMinutes()) {
                open(alerts, s, "REPOSITIONING_REVIEW",
                        "Repositioning review due. No confirmed repositioning has been documented within the configured care-plan interval.",
                        "Last documented repositioning " + fmt(last) + " (" + since + " min ago; interval " + plan.repositioningIntervalMinutes() + " min)", now);
            } else {
                resolveOpen(alerts, "REPOSITIONING_REVIEW", now, "System", "Repositioning documented at " + fmt(last));
            }
        }
    }

    private boolean open(List<Alert> existing, Session s, String type, String message, String basis, LocalDateTime now) {
        boolean already = existing.stream().anyMatch(a -> a.alertType().equals(type) && !a.status().equals("RESOLVED"));
        if (already) return false;
        repo.insertAlert(new Alert(SupportRepository.newId("MAL"), s.sessionId(), s.patientId(), s.encounterId(), type, "OPEN",
                message, basis, now, LocalDateTime.now(), "System", null));
        return true;
    }

    private void resolveOpen(List<Alert> existing, String type, LocalDateTime now, String actor, String resolution) {
        existing.stream().filter(a -> a.alertType().equals(type) && !a.status().equals("RESOLVED"))
                .forEach(a -> repo.updateAlertStatus(a.alertId(), "RESOLVED", LocalDateTime.now(), actor, resolution + " (simulated time)"));
    }

    private LocalDateTime lastWalkEnd(Session s) {
        return repo.events(s.patientId(), s.encounterId(), null, s.simClockAt()).stream()
                .filter(e -> e.eventType().equals("WALKING"))
                .map(e -> e.endedAt() != null ? e.endedAt() : e.startedAt())
                .max(Comparator.naturalOrder()).orElse(s.startedAt());
    }

    private LocalDateTime lastRepositioning(Session s) {
        return repo.interventions(s.patientId(), s.encounterId()).stream()
                .filter(i -> i.type().equals("REPOSITIONING") && !i.performedAt().isAfter(s.simClockAt()))
                .map(Intervention::performedAt).max(Comparator.naturalOrder()).orElse(s.startedAt());
    }

