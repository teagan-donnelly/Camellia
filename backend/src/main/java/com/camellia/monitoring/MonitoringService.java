    /** Creates the seeded monitoring scenarios for encounters that exist and have no session yet. Idempotent. */
    public int seedBaseline(LocalDate anchor) {
        int created = 0;
        for (Scenario s : SCENARIOS) {
            Encounter enc = clinical.findEncounter(s.encounterId()).orElse(null);
            if (enc == null || !enc.patientId().equals(s.patientId())) continue;
            if (!repo.sessionsForEncounter(s.patientId(), s.encounterId()).isEmpty()) continue;
            generateScenario(s, enc, initialClock(anchor, enc));
            created++;
        }
        if (created > 0) log.info("Seeded {} simulated monitoring scenario(s)", created);
        return created;
    }

    /** The simulation starts at 14:00 hospital time on the demo anchor date (stored as UTC like all timestamps). */
    LocalDateTime initialClock(LocalDate anchor, Encounter enc) {
        LocalDateTime clock = anchor.atTime(14, 0).atZone(hospitalZone()).withZoneSameInstant(ZoneOffset.UTC).toLocalDateTime();
        return enc.startTime() != null && clock.isBefore(enc.startTime().plusHours(4)) ? enc.startTime().plusHours(4) : clock;
    }

    private void generateScenario(Scenario s, Encounter enc, LocalDateTime now) {
        ensureDevice(s.deviceId());
        long seed = Objects.hash(s.encounterId(), "camellia-sim") & 0x7fffffffL;
        Random rng = new Random(seed);
        LocalDateTime start = enc.startTime().plusMinutes(90);
        String sessionId = "MS-" + s.encounterId().replace("ENC-", "");
        repo.insertPlan(new CarePlan(SupportRepository.newId("PLAN"), s.patientId(), s.encounterId(), s.mobilityMinutes(),
                s.repositioningMinutes(), props.getMonitoring().getStaleDataMinutes(), s.planNote(), "Nursing care plan (seed)"));

        List<ActivityEvent> events = new ArrayList<>();
        List<LocalDateTime[]> walks = new ArrayList<>();
        LocalDateTime dataEnd = now;
        boolean connected = true;

        switch (s.kind()) {
            case "MOBILITY", "CONNECTIVITY" -> {
                // Walks while awake, working backwards from a last walk 150 min (mobility) or 5 h (connectivity) ago.
                LocalDateTime end = now.minusMinutes(s.kind().equals("MOBILITY") ? 150 : 300);
                while (end.isAfter(start.plusMinutes(30))) {
                    int hour = end.atZone(ZoneOffset.UTC).withZoneSameInstant(hospitalZone()).getHour();
                    if (hour >= 8 && hour <= 21) {
                        int minutes = 4 + rng.nextInt(7);
                        walks.add(new LocalDateTime[]{end.minusMinutes(minutes), end});
                        end = end.minusMinutes(200 + rng.nextInt(70));
                    } else {
                        end = end.minusMinutes(60);
                    }
                }
                Collections.reverse(walks);
                for (LocalDateTime[] w : walks) {
                    events.add(event(sessionId, s, "WALKING", w[0], w[1], "SENSOR",
                            "Walking detected (device-estimated) for about " + minutesBetween(w[0], w[1]) + " min", null));
                }
                if (s.kind().equals("CONNECTIVITY")) {
                    dataEnd = now.minusMinutes(50);
                    connected = false;
                    events.add(event(sessionId, s, "DEVICE_DISCONNECTED", dataEnd, null, "SYSTEM",
                            "Wristband stopped syncing with the gateway (simulated)", null));
                }
            }
            case "REPOSITIONING" -> {
                // Confirmed repositioning every ~2 h, documented by nursing; the most recent one was 95 min ago.
                DemoUser nurse = cedarHollowNurse();
                LocalDateTime t = now.minusMinutes(95);
                List<LocalDateTime> times = new ArrayList<>();
                while (t.isAfter(start)) {
                    times.add(t);
                    t = t.minusMinutes(110 + rng.nextInt(20));
                }
                Collections.reverse(times);
                for (LocalDateTime at : times) {
                    String id = SupportRepository.newId("INT");
                    repo.insertIntervention(new Intervention(id, s.patientId(), s.encounterId(), "REPOSITIONING", at, nurse.id(),
                            nurse.name(), "Log-roll repositioning (seeded documentation)", at));
                    events.add(event(sessionId, s, "REPOSITIONING_DOCUMENTED", at, null, "NURSE",
                            "Repositioning documented by " + nurse.name(), nurse.name()));
                }
                // Estimated wrist movement — shown separately and never counted as repositioning.
                LocalDateTime m = start.plusMinutes(40);
                while (m.isBefore(now)) {
                    events.add(event(sessionId, s, rng.nextInt(3) == 0 ? "POSSIBLE_POSITION_CHANGE" : "MOVEMENT", m, null,
                            "SENSOR", rng.nextInt(3) == 0 ? "Possible position change (device estimate)" : "Arm movement detected", null));
                    m = m.plusMinutes(45 + rng.nextInt(50));
                }
            }
            default -> { }
        }

        List<Observation> obs = new ArrayList<>();
        for (LocalDateTime t = start; !t.isAfter(dataEnd); t = t.plusMinutes(VITALS_EVERY_MINUTES)) {
            boolean walking = inWalk(walks, t);
            obs.addAll(vitals(sessionId, s.patientId(), s.encounterId(), s.deviceId(), t, rng, s.heartRate(), s.spo2(),
                    s.skinTemp(), walking));
            if (t.getMinute() < VITALS_EVERY_MINUTES) obs.add(battery(sessionId, s, t, start));
        }
        repo.insertObservations(obs);
        repo.insertEvents(events);
        Session session = new Session(sessionId, s.patientId(), s.encounterId(), s.deviceId(), start, null, "ACTIVE", connected,
                dataEnd, batteryAt(start, dataEnd), now, seed, s.kind());
        repo.insertSession(session);
        evaluate(session, "System (seed)");
    }

    private DemoUser cedarHollowNurse() {
        return DemoDirectory.CLINICIANS.stream()
                .filter(c -> c.user().role().name().equals("REGISTERED_NURSE") && "CHCH".equals(c.orgId()))
                .map(DemoDirectory.Clinician::user).findFirst().orElse(DemoDirectory.require("jordan.lee"));
    }

    private void ensureDevice(String deviceId) {
        if (!repo.existingDeviceIds().contains(deviceId)) {
            repo.insertDevice(new Device(deviceId, "Camellia wristband prototype — MPU-6050 IMU + MAX30102 optical + ESP32 (SIMULATED)",
                    "sim-0.3", true));
        }
    }

