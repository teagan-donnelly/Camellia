    private List<WalkingBucket> walkingBuckets(List<ActivityEvent> events, LocalDateTime from, LocalDateTime to, boolean hourly) {
        ZoneId zone = hospitalZone();
        TreeMap<LocalDateTime, Integer> buckets = new TreeMap<>();
        ZonedDateTime cursor = from.atZone(ZoneOffset.UTC).withZoneSameInstant(zone);
        cursor = hourly ? cursor.truncatedTo(ChronoUnit.HOURS) : cursor.toLocalDate().atStartOfDay(zone);
        ZonedDateTime end = to.atZone(ZoneOffset.UTC).withZoneSameInstant(zone);
        while (!cursor.isAfter(end)) {
            buckets.put(cursor.withZoneSameInstant(ZoneOffset.UTC).toLocalDateTime(), 0);
            cursor = hourly ? cursor.plusHours(1) : cursor.plusDays(1);
        }
        for (ActivityEvent e : events) {
            if (!e.eventType().equals("WALKING") || e.durationSeconds() == null) continue;
            Map.Entry<LocalDateTime, Integer> b = buckets.floorEntry(e.startedAt());
            if (b != null) buckets.put(b.getKey(), b.getValue() + e.durationSeconds());
        }
        DateTimeFormatter f = DateTimeFormatter.ofPattern(hourly ? "MMM d HH:mm" : "MMM d");
        return buckets.entrySet().stream().map(en -> new WalkingBucket(en.getKey(),
                en.getKey().atZone(ZoneOffset.UTC).withZoneSameInstant(zone).format(f), Math.round(en.getValue() / 60f))).toList();
    }

    static String label(String type) {
        if (type == null) return "";
        return switch (type) {
            case "WALKING" -> "Walking detected";
            case "MOVEMENT" -> "Movement detected";
            case "POSSIBLE_POSITION_CHANGE" -> "Possible position change";
            case "INACTIVITY_REVIEW" -> "Inactivity review triggered";
            case "DEVICE_DISCONNECTED" -> "Device disconnected";
            case "DEVICE_RECONNECTED" -> "Device reconnected";
            case "REPOSITIONING_DOCUMENTED" -> "Nursing repositioning documented";
            case "SESSION_STARTED" -> "Monitoring session started";
            case "SESSION_STOPPED" -> "Monitoring session stopped";
            case "MOBILITY_REVIEW" -> "Mobility review";
            case "REPOSITIONING_REVIEW" -> "Repositioning review";
            case "DEVICE_CONNECTIVITY" -> "Device connectivity";
            case "HEART_RATE" -> "Heart rate";
            case "SPO2" -> "SpO2";
            case "SKIN_TEMP" -> "Skin temperature";
            default -> type;
        };
    }

    private static String typeCode(String type) {
        return switch (type) {
            case "HEART_RATE" -> "HR";
            case "SPO2" -> "SPO2";
            default -> "TEMP";
        };
    }

    private String fmt(LocalDateTime t) {
        if (t == null) return "unknown";
        return t.atZone(ZoneOffset.UTC).withZoneSameInstant(hospitalZone()).format(DateTimeFormatter.ofPattern("MMM d HH:mm z", Locale.US));
    }

    private static String readingText(Reading r) {
        return r == null ? "not available" : num(r.value()) + " " + r.unit();
    }

    private static String num(double v) {
        return v == Math.floor(v) ? String.valueOf((long) v) : String.format(Locale.ROOT, "%.1f", v);
    }

    private static long minutesBetween(LocalDateTime a, LocalDateTime b) {
        return Duration.between(a, b).toMinutes();
    }

    private static int clamp(Integer v, int min, int max, int dflt) {
        if (v == null) return dflt;
        if (v < min || v > max) throw ApiException.badRequest("minutes must be between " + min + " and " + max);
        return v;
    }
