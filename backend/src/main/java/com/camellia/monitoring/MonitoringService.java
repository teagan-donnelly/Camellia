    public ObservationSeries observations(DemoUser user, String patientId, String encounterId, String range) {
        Scoped sc = resolve(user, patientId, encounterId);
        Session s = activeOrLatest(sc).orElse(null);
        Encounter e = sc.encounter();
        LocalDateTime to = s != null ? s.simClockAt() : (e.endTime() != null ? e.endTime() : LocalDateTime.now());
        String r = range == null ? "24h" : range.toLowerCase(Locale.ROOT);
        LocalDateTime from = switch (r) {
            case "24h" -> to.minusHours(24);
            case "7d" -> to.minusDays(7);
            case "stay" -> e.startTime();
            default -> throw ApiException.badRequest("range must be 24h, 7d or stay");
        };
        if (from.isBefore(e.startTime())) from = e.startTime();        // never outside this stay
        if (e.endTime() != null && to.isAfter(e.endTime())) to = e.endTime();
        Map<String, List<Point>> series = new LinkedHashMap<>();
        VITAL_TYPES.forEach(t -> series.put(t, new ArrayList<>()));
        for (Observation o : repo.observations(patientId, encounterId, from, to, null)) {
            if (series.containsKey(o.type())) series.get(o.type()).add(new Point(o.observedAt(), o.value(), o.quality()));
        }
        boolean hourly = Duration.between(from, to).toHours() <= 48;
        List<WalkingBucket> walking = walkingBuckets(repo.events(patientId, encounterId, from, to), from, to, hourly);
        return new ObservationSeries(r, from, to, hourly ? "HOUR" : "DAY", series, UNITS, walking, to, NOTICE);
    }

