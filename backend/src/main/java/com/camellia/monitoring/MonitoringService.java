    private List<Observation> vitals(String sessionId, String patientId, String encounterId, String deviceId, LocalDateTime t,
                                     Random rng, int hrBase, double spo2Base, double tempBase, boolean walking) {
        int hour = t.atZone(ZoneOffset.UTC).withZoneSameInstant(hospitalZone()).getHour();
        double circadian = (hour >= 0 && hour < 6) ? -6 : 0;
        double hr = hrBase + circadian + (walking ? 14 + rng.nextInt(8) : 0) + rng.nextGaussian() * 3;
        double spo2 = Math.min(100, spo2Base + rng.nextGaussian() * 0.7 - (walking ? 0.8 : 0));
        double temp = tempBase + rng.nextGaussian() * 0.25 + (walking ? 0.3 : 0);
        String quality = walking && rng.nextInt(4) == 0 ? "FAIR" : "GOOD";
        return List.of(
                obs(sessionId, patientId, encounterId, deviceId, t, "HEART_RATE", Math.round(hr), quality),
                obs(sessionId, patientId, encounterId, deviceId, t, "SPO2", Math.round(spo2 * 10) / 10.0, quality),
                obs(sessionId, patientId, encounterId, deviceId, t, "SKIN_TEMP", Math.round(temp * 10) / 10.0, "GOOD"));
    }

