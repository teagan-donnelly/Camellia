    MonitoringCard card(Session s) {
        LocalDateTime now = s.simClockAt();
        ZonedDateTime localNow = now.atZone(ZoneOffset.UTC).withZoneSameInstant(hospitalZone());
        LocalDateTime dayStart = localNow.toLocalDate().atStartOfDay(hospitalZone()).withZoneSameInstant(ZoneOffset.UTC).toLocalDateTime();
        List<ActivityEvent> events = repo.events(s.patientId(), s.encounterId(), null, now);
        int walkingToday = events.stream().filter(e -> e.eventType().equals("WALKING") && !e.startedAt().isBefore(dayStart))
                .mapToInt(e -> e.durationSeconds() == null ? 0 : e.durationSeconds()).sum() / 60;
        ActivityEvent last = events.stream().filter(e -> SENSOR_ACTIVITY.contains(e.eventType()))
                .max(Comparator.comparing(ActivityEvent::startedAt)).orElse(null);
        CarePlan plan = repo.plan(s.patientId(), s.encounterId()).orElse(null);
        int staleMinutes = plan != null && plan.staleDataMinutes() != null ? plan.staleDataMinutes() : props.getMonitoring().getStaleDataMinutes();
        boolean stale = s.lastSyncAt() == null || Duration.between(s.lastSyncAt(), now).toMinutes() > staleMinutes;
        String deviceStatus = !s.active() ? "STOPPED" : !s.connected() ? "DISCONNECTED" : stale ? "STALE" : "CONNECTED";
        int open = (int) repo.alerts(s.patientId(), s.encounterId()).stream().filter(a -> !a.status().equals("RESOLVED")).count();
        return new MonitoringCard(s.sessionId(), s.status(), deviceStatus, now, walkingToday,
                last == null ? null : (last.endedAt() != null ? last.endedAt() : last.startedAt()),
                last == null ? null : last.eventType(), reading(s, "HEART_RATE"), reading(s, "SPO2"), reading(s, "SKIN_TEMP"),
                s.batteryPct(), s.lastSyncAt(), stale || !s.connected(), open);
    }

