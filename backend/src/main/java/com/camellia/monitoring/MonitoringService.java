    /** Nursing work queue: monitored stays and monitoring alerts within the user's patient scope. */
    public NursingQueue queue(DemoUser user) {
        auth.requirePermission(user, Permission.NURSING_MONITORING);
        AccessScope scope = auth.scope(user);
        Map<String, Patient> pts = patients.findAll().stream().collect(Collectors.toMap(Patient::patientId, p -> p));
        Map<String, String> orgNames = orgNames();
        Map<String, Encounter> encs = new HashMap<>();
        List<QueuePatient> monitored = new ArrayList<>();
        for (Session s : repo.allSessions()) {
            if (!scope.allowsPatient(s.patientId()) || !s.active()) continue;
            Encounter e = encs.computeIfAbsent(s.encounterId(), id -> clinical.findEncounter(id).orElse(null));
            Patient p = pts.get(s.patientId());
            if (e == null || p == null) continue;
            CarePlan plan = repo.plan(s.patientId(), s.encounterId()).orElse(null);
            LocalDateTime nextRepo = plan == null || plan.repositioningIntervalMinutes() == null ? null
                    : lastRepositioning(s).plusMinutes(plan.repositioningIntervalMinutes());
            LocalDateTime nextMob = plan == null || plan.mobilityReviewMinutes() == null ? null
                    : lastWalkEnd(s).plusMinutes(plan.mobilityReviewMinutes());
            monitored.add(new QueuePatient(p.patientId(), p.fullName(), p.displayId(), e.encounterId(), orgNames.get(e.orgId()),
                    e.department(), e.startTime(), card(s), nextRepo, nextMob));
        }
        List<QueueAlert> alerts = repo.allAlerts().stream().filter(a -> scope.allowsPatient(a.patientId())).map(a -> {
            Patient p = pts.get(a.patientId());
            Encounter e = encs.computeIfAbsent(a.encounterId(), id -> clinical.findEncounter(id).orElse(null));
            return new QueueAlert(a, p == null ? a.patientId() : p.fullName(), p == null ? null : p.displayId(),
                    e == null ? null : orgNames.get(e.orgId()), e == null ? null : e.department());
        }).toList();
        return new NursingQueue(monitored, alerts, NOTICE);
    }

