    public record SimulatorRequest(String patientId, String encounterId, String action, Integer minutes) {}

    public MonitoringDetail simulate(DemoUser user, SimulatorRequest req) {
        if (!props.getMonitoring().isSimulatorEnabled()) {
            throw new ApiException(HttpStatus.FORBIDDEN, "SIMULATOR_DISABLED", "The wristband simulator is turned off in this deployment.");
        }
        auth.requirePermission(user, Permission.SIMULATE_DEVICES);
        if (req == null || req.action() == null) throw ApiException.badRequest("action is required");
        Scoped sc = resolve(user, req.patientId(), req.encounterId());
        String action = req.action().trim().toUpperCase(Locale.ROOT);
        Session s = activeOrLatest(sc).orElse(null);

        if (action.equals("START_SESSION")) {
            startSession(sc, s, user);
            return detail(user, sc.patient().patientId(), sc.encounter().encounterId());
        }
        if (s == null) throw ApiException.badRequest("No monitoring session exists for this hospital stay. Start one first.");
        if (!s.active() && !action.equals("RESET")) {
            throw ApiException.badRequest("The monitoring session is stopped. Start it again before generating readings.");
        }
        Random rng = new Random(s.simSeed() ^ s.simClockAt().toEpochSecond(ZoneOffset.UTC));
        LocalDateTime now = s.simClockAt();
        Scenario profile = profile(sc);
        switch (action) {
            case "WALK" -> {
                int minutes = clamp(req.minutes(), 1, 60, 6);
                requireConnected(s, "walking");
                LocalDateTime end = now.plusMinutes(minutes);
                List<Observation> obs = new ArrayList<>();
                for (LocalDateTime t = now.plusMinutes(5); !t.isAfter(end); t = t.plusMinutes(5)) {
                    obs.addAll(vitals(s.sessionId(), s.patientId(), s.encounterId(), s.deviceId(), t, rng, profile.heartRate(),
                            profile.spo2(), profile.skinTemp(), true));
                }
                repo.insertObservations(obs);
                repo.insertEvents(List.of(event(s, "WALKING", now, end, "SENSOR",
                        "Walking detected (device-estimated) for about " + minutes + " min", null)));
                s = s.with(s.status(), true, end, batteryAt(s.startedAt(), end), end, null);
            }
            case "VITALS" -> {
                requireConnected(s, "vital-sign readings");
                repo.insertObservations(vitals(s.sessionId(), s.patientId(), s.encounterId(), s.deviceId(), now, rng,
                        profile.heartRate(), profile.spo2(), profile.skinTemp(), false));
                s = s.with(s.status(), true, now, batteryAt(s.startedAt(), now), now, null);
            }
            case "MOVEMENT", "POSITION_CHANGE" -> {
                requireConnected(s, "movement events");
                String type = action.equals("MOVEMENT") ? "MOVEMENT" : "POSSIBLE_POSITION_CHANGE";
                repo.insertEvents(List.of(event(s, type, now, null, "SENSOR", type.equals("MOVEMENT")
                        ? "Arm movement detected" : "Possible position change (device estimate — not confirmed repositioning)", null)));
                s = s.with(s.status(), true, now, s.batteryPct(), now, null);
            }
            case "DISCONNECT" -> {
                if (!s.connected()) throw ApiException.badRequest("The device is already disconnected.");
                repo.insertEvents(List.of(event(s, "DEVICE_DISCONNECTED", now, null, "SYSTEM",
                        "Wristband stopped syncing with the gateway (simulated)", null)));
                s = s.with(s.status(), false, s.lastSyncAt(), s.batteryPct(), now, null);
            }
            case "RECONNECT" -> {
                if (s.connected()) throw ApiException.badRequest("The device is already connected.");
                repo.insertEvents(List.of(event(s, "DEVICE_RECONNECTED", now, null, "SYSTEM",
                        "Wristband reconnected; readings resumed (simulated)", null)));
                repo.insertObservations(vitals(s.sessionId(), s.patientId(), s.encounterId(), s.deviceId(), now, rng,
                        profile.heartRate(), profile.spo2(), profile.skinTemp(), false));
                s = s.with(s.status(), true, now, batteryAt(s.startedAt(), now), now, null);
            }
            case "STOP_SESSION" -> {
                repo.insertEvents(List.of(event(s, "SESSION_STOPPED", now, null, "SYSTEM", "Monitoring session stopped", user.name())));
                s = s.with("STOPPED", s.connected(), s.lastSyncAt(), s.batteryPct(), now, now);
            }
            case "ADVANCE_TIME" -> s = advance(s, clamp(req.minutes(), 1, MAX_ADVANCE_MINUTES, 60), rng, profile);
            case "SCENARIO_INACTIVITY" -> {
                CarePlan plan = repo.plan(s.patientId(), s.encounterId()).orElse(null);
                if (plan == null || plan.mobilityReviewMinutes() == null) {
                    throw ApiException.badRequest("This stay has no mobility plan, so no mobility review can be triggered.");
                }
                requireConnected(s, "an inactivity scenario");
                LocalDateTime lastWalk = lastWalkEnd(s);
                long needed = plan.mobilityReviewMinutes() - Duration.between(lastWalk, now).toMinutes() + 5;
                s = advance(s, (int) Math.max(5, Math.min(needed, MAX_ADVANCE_MINUTES)), rng, profile);
            }
            case "SCENARIO_REPOSITIONING_DUE" -> {
                CarePlan plan = repo.plan(s.patientId(), s.encounterId()).orElse(null);
                if (plan == null || plan.repositioningIntervalMinutes() == null) {
                    throw ApiException.badRequest("This stay has no repositioning plan.");
                }
                LocalDateTime last = lastRepositioning(s);
                long needed = plan.repositioningIntervalMinutes() - Duration.between(last, now).toMinutes() + 5;
                s = advance(s, (int) Math.max(5, Math.min(needed, MAX_ADVANCE_MINUTES)), rng, profile);
            }
            case "RESET" -> {
                resetScenario(sc);
                return detail(user, sc.patient().patientId(), sc.encounter().encounterId());
            }
            default -> throw ApiException.badRequest("Unknown simulator action " + req.action());
        }
        repo.updateSession(s);
        evaluate(s, user.name());
        support.logActivity("MONITORING", s.sessionId(), s.patientId(), "SIMULATOR_" + action,
                "Simulator action " + action + " on encounter " + s.encounterId(), user.name());
        return detail(user, sc.patient().patientId(), sc.encounter().encounterId());
    }

    private Session advance(Session s, int minutes, Random rng, Scenario profile) {
        LocalDateTime from = s.simClockAt();
        LocalDateTime to = from.plusMinutes(minutes);
        LocalDateTime lastSync = s.lastSyncAt();
        if (s.connected()) {
            List<Observation> obs = new ArrayList<>();
            LocalDateTime t = from.truncatedTo(ChronoUnit.HOURS);
            while (!t.isAfter(from)) t = t.plusMinutes(VITALS_EVERY_MINUTES);
            for (; !t.isAfter(to); t = t.plusMinutes(VITALS_EVERY_MINUTES)) {
                obs.addAll(vitals(s.sessionId(), s.patientId(), s.encounterId(), s.deviceId(), t, rng, profile.heartRate(),
                        profile.spo2(), profile.skinTemp(), false));
                if (t.getMinute() == 0) {
                    obs.add(new Observation(SupportRepository.newId("OBS"), s.sessionId(), s.patientId(), s.encounterId(),
                            s.deviceId(), t, "BATTERY", batteryAt(s.startedAt(), t), "%", "SIMULATED_DEVICE", "GOOD"));
                }
                lastSync = t;
            }
            repo.insertObservations(obs);
        }
        return s.with(s.status(), s.connected(), lastSync, s.connected() ? batteryAt(s.startedAt(), to) : s.batteryPct(), to, null);
    }

    private void startSession(Scoped sc, Session existing, DemoUser user) {
        Encounter enc = sc.encounter();
        if (!enc.inpatient()) throw ApiException.badRequest("Wristband monitoring is only available for hospital stays.");
        if (existing != null && existing.active()) throw ApiException.badRequest("A monitoring session is already active for this stay.");
        if (existing != null) {
            Session restarted = existing.with("ACTIVE", true, existing.simClockAt(), existing.batteryPct(), existing.simClockAt(), null);
            repo.updateSession(restarted);
            repo.insertEvents(List.of(event(restarted, "SESSION_STARTED", restarted.simClockAt(), null, "SYSTEM",
                    "Monitoring session restarted", user.name())));
            return;
        }
        LocalDate anchor = support.getMeta("ANCHOR_DATE").map(LocalDate::parse).orElse(LocalDate.now());
        LocalDateTime now = initialClock(anchor, enc);
        if (!enc.ongoingAt(now)) throw ApiException.badRequest("Monitoring can only start during an ongoing hospital stay.");
        String deviceId = "WB-SIM-" + Integer.toHexString(enc.encounterId().hashCode()).toUpperCase(Locale.ROOT);
        ensureDevice(deviceId);
        Session s = new Session("MS-" + enc.encounterId().replace("ENC-", ""), enc.patientId(), enc.encounterId(), deviceId, now,
                null, "ACTIVE", true, now, 100.0, now, Objects.hash(enc.encounterId()) & 0x7fffffffL, "MANUAL");
        repo.insertSession(s);
        repo.insertEvents(List.of(event(s, "SESSION_STARTED", now, null, "SYSTEM", "Monitoring session started (no care plan "
                + "intervals configured, so no mobility or repositioning reviews will be generated)", user.name())));
        repo.insertPlan(new CarePlan(SupportRepository.newId("PLAN"), enc.patientId(), enc.encounterId(), null, null,
                props.getMonitoring().getStaleDataMinutes(), "Monitoring only — no mobility or repositioning interval configured",
                user.name()));
    }

    private void resetScenario(Scoped sc) {
        String pid = sc.patient().patientId(), eid = sc.encounter().encounterId();
        repo.deleteSimulatedData(pid, eid);
        Scenario s = SCENARIOS.stream().filter(x -> x.encounterId().equals(eid)).findFirst().orElse(null);
        if (s != null) {
            LocalDate anchor = support.getMeta("ANCHOR_DATE").map(LocalDate::parse).orElse(LocalDate.now());
            generateScenario(s, sc.encounter(), initialClock(anchor, sc.encounter()));
        }
    }

    private Scenario profile(Scoped sc) {
        return SCENARIOS.stream().filter(x -> x.encounterId().equals(sc.encounter().encounterId())).findFirst()
                .orElse(new Scenario(sc.encounter().encounterId(), sc.patient().patientId(), null, "MANUAL", null, null, null, 80, 96.5, 33.5));
    }

    private static void requireConnected(Session s, String what) {
        if (!s.connected()) throw ApiException.badRequest("The device is disconnected, so it cannot report " + what + ". Reconnect it first.");
    }

