    public record Scoped(Patient patient, Encounter encounter) {}

    /** Verifies permission, patient scope, and that the encounter belongs to the patient. Generic 403 otherwise. */
    public Scoped resolve(DemoUser user, String patientId, String encounterId) {
        auth.requirePermission(user, Permission.VIEW_MONITORING);
        auth.requirePatient(user, patientId);
        Encounter enc = clinical.findEncounter(encounterId).orElse(null);
        if (enc == null || !enc.patientId().equals(patientId)) throw AuthorizationService.denied(null);
        return new Scoped(patients.findById(patientId).orElseThrow(), enc);
    }

