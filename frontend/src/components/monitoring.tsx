import { Activity, BatteryMedium, ChevronRight, HeartPulse, Radio, Thermometer, Wifi, WifiOff, Wind } from 'lucide-react'
import { Link } from 'react-router-dom'
import type { EncounterView, MonitoringAlert, MonitoringCard } from '../api/types'
import { MONITORING_LABEL, cx, fmtDate, fmtHospital, sinceSim } from '../lib/format'
import { Badge } from './ui'

export function DeviceStatusBadge({ status }: { status: MonitoringCard['deviceStatus'] }) {
  switch (status) {
    case 'CONNECTED': return <Badge tone="sage"><Wifi className="h-3 w-3" />Connected</Badge>
    case 'STALE': return <Badge tone="amber"><Radio className="h-3 w-3" />Data stale</Badge>
    case 'DISCONNECTED': return <Badge tone="amber"><WifiOff className="h-3 w-3" />Disconnected</Badge>
    default: return <Badge tone="neutral">Session stopped</Badge>
  }
}

export function MonitoringAlertBadge({ alert }: { alert: Pick<MonitoringAlert, 'alertType' | 'status'> }) {
  const tone = alert.status === 'RESOLVED' ? 'neutral' : alert.alertType === 'DEVICE_CONNECTIVITY' ? 'navy' : 'amber'
  return <Badge tone={tone}>{MONITORING_LABEL[alert.alertType]} · {alert.status.toLowerCase()}</Badge>
}

export function SimulatedTag({ className }: { className?: string }) {
  return (
    <span title="Generated by Camellia's Java wristband simulator. Device-estimated values, not validated clinical measurements."
      className={cx('rounded bg-amber-50 px-1.5 py-0.5 text-[10.5px] font-semibold uppercase tracking-wide text-amber-700 ring-1 ring-inset ring-amber-200', className)}>
      Simulated device data
    </span>
  )
}

const stayRange = (e: EncounterView) => `${fmtDate(e.startTime)} – ${e.endTime ? fmtDate(e.endTime) : 'present'}`

/**
 * "Patient Monitoring" card for one monitored hospital stay. Rendered only for encounters that have a monitoring
 * session (the caller filters), and shows a stale/unavailable state instead of numbers when readings are not current.
 */
export function PatientMonitoringCard({ patientId, encounter, fromTab, tz = 'America/New_York' }: {
  patientId: string; encounter: EncounterView; fromTab?: string; tz?: string
}) {
  const c = encounter.monitoring!
  const unavailable = c.deviceStatus !== 'CONNECTED'
  return (
    <div className="rounded-xl border border-line bg-white p-4 shadow-[0_1px_2px_rgba(16,24,40,0.04)]">
      <div className="flex flex-wrap items-start justify-between gap-2">
        <div>
          <div className="flex items-center gap-2 text-[14.5px] font-semibold text-navy-900"><Activity className="h-4 w-4 text-coral-600" />Patient Monitoring</div>
          <div className="mt-0.5 text-[12.5px] text-navy-500">{encounter.orgName} · {encounter.department}</div>
          <div className="text-[12.5px] text-navy-500">Stay: {stayRange(encounter)}</div>
        </div>
        <div className="flex flex-col items-end gap-1"><DeviceStatusBadge status={c.deviceStatus} /><SimulatedTag /></div>
      </div>
      {unavailable && (
        <div className="mt-3 rounded-lg bg-amber-50 px-3 py-2 text-[12.5px] text-amber-800">
          {c.deviceStatus === 'STOPPED' ? 'The monitoring session is stopped.' : 'No current readings — the device is ' + (c.deviceStatus === 'DISCONNECTED' ? 'disconnected' : 'not syncing') + '.'}
          {' '}Last sync {fmtHospital(c.lastSyncAt, tz)}. Values below are the last received and may be out of date.
        </div>
      )}
      <dl className="mt-3 grid grid-cols-2 gap-x-4 gap-y-2.5 text-[13px] sm:grid-cols-3">
        <Metric icon={<Activity className="h-3.5 w-3.5" />} label="Walking today" value={`${c.walkingTodayMinutes} min`} />
        <Metric icon={<Activity className="h-3.5 w-3.5" />} label="Last detected activity" value={c.lastActivityAt ? fmtHospital(c.lastActivityAt, tz, false) : 'None'}
          hint={c.lastActivityAt ? sinceSim(c.lastActivityAt, c.simulatedNow) : undefined} />
        <Metric icon={<HeartPulse className="h-3.5 w-3.5" />} label="Latest heart rate" value={c.latestHeartRate ? `${c.latestHeartRate.value} bpm` : '—'} stale={unavailable} />
        <Metric icon={<Wind className="h-3.5 w-3.5" />} label="Latest SpO₂" value={c.latestSpo2 ? `${c.latestSpo2.value}%` : '—'} stale={unavailable} />
        <Metric icon={<Thermometer className="h-3.5 w-3.5" />} label="Skin temperature" value={c.latestSkinTemp ? `${c.latestSkinTemp.value} °C` : '—'} stale={unavailable} />
        <Metric icon={<BatteryMedium className="h-3.5 w-3.5" />} label="Battery" value={c.batteryPct != null ? `${Math.round(c.batteryPct)}%` : '—'} />
      </dl>
      <div className="mt-3 flex items-center justify-between border-t border-line pt-3">
        <span className="text-[12px] text-navy-500">{c.openAlerts ? `${c.openAlerts} open nursing review${c.openAlerts === 1 ? '' : 's'}` : 'No open reviews'} · simulated time {fmtHospital(c.simulatedNow, tz)}</span>
        <Link to={`/patients/${patientId}/encounters/${encounter.encounterId}/monitoring${fromTab ? `?from=${fromTab}` : ''}`}
          className="inline-flex items-center gap-1 text-[13px] font-medium text-coral-700 hover:text-coral-800">
          View Monitoring Details <ChevronRight className="h-3.5 w-3.5" />
        </Link>
      </div>
    </div>
  )
}

function Metric({ icon, label, value, hint, stale }: { icon: React.ReactNode; label: string; value: string; hint?: string; stale?: boolean }) {
  return (
    <div>
      <dt className="flex items-center gap-1 text-[11.5px] text-navy-400">{icon}{label}</dt>
      <dd className={cx('font-semibold text-navy-900', stale && 'text-navy-400')}>{value}</dd>
      {hint && <dd className="text-[11px] text-navy-400">{hint}</dd>}
    </div>
  )
}
