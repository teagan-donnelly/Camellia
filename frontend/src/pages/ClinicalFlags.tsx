import { ChevronDown, Info, PlayCircle, Search, X } from 'lucide-react'
import { useEffect, useState } from 'react'
import { useSearchParams } from 'react-router-dom'
import { useFlagFacets, useFlagSearch, useRules, useRunAnalysis } from '../api/hooks'
import { FlagHitCard } from '../components/flags'
import { Badge, Button, Card, EmptyState, ErrorBox, Loading, PageHeader, Tabs } from '../components/ui'
import { FLAG_STATUS_LABEL, cx, titleCase } from '../lib/format'
import { useApp } from '../state/AppContext'

type Group = 'OPEN' | 'CLOSED' | 'ANY'
const FILTER_KEYS = ['q', 'category', 'status', 'priority', 'specialty'] as const

/** Clinical Alerts (formerly "Clinical Flags"): structured, server-side search over the alerts the user may see. */
export default function ClinicalFlags() {
  const [params, setParams] = useSearchParams()
  const group = (params.get('statusGroup') as Group) || 'OPEN'
  const [text, setText] = useState(params.get('q') ?? '')
  const facets = useFlagFacets()
  const rules = useRules()
  const run = useRunAnalysis()
  const { toast } = useApp()
  const [showRules, setShowRules] = useState(false)

  const query = new URLSearchParams()
  query.set('statusGroup', group)
  for (const k of FILTER_KEYS) {
    const v = params.get(k)
    if (v) query.set(k, v)
  }
  const { data, isLoading, isFetching, error } = useFlagSearch(query.toString())

  const setParam = (k: string, v: string) => {
    const next = new URLSearchParams(params)
    if (v) next.set(k, v)
    else next.delete(k)
    setParams(next, { replace: true })
  }

  // Debounce free-text search so each keystroke does not hit the backend.
  useEffect(() => {
    const t = setTimeout(() => { if ((params.get('q') ?? '') !== text.trim()) setParam('q', text.trim()) }, 300)
    return () => clearTimeout(t)
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [text])

  const active = FILTER_KEYS.filter((k) => params.get(k))

  return (
    <div>
      <PageHeader eyebrow="Feature B" title="Clinical Alerts"
        subtitle="Candidate review items generated by explainable, deterministic screening rules. Each alert cites the exact source records that triggered it. Results are limited to the patients and alert types your role may access."
        actions={<Button variant="navy" loading={run.isPending} onClick={() => run.mutate(undefined, {
          onSuccess: (r) => toast({ tone: 'success', title: 'Screening run complete', body: `${r.flagsCreated} new · ${r.flagsUpdated} updated · ${r.flagsUnchanged} unchanged — duplicate alerts are never created.` }),
          onError: (e) => toast({ tone: 'error', title: 'Screening failed', body: (e as Error).message }),
        })}><PlayCircle className="h-4 w-4" />Run screening</Button>} />

      <Card className="mb-5" padded={false}>
        <button onClick={() => setShowRules((s) => !s)} className="flex w-full items-center gap-2 px-5 py-3 text-left">
          <Info className="h-4 w-4 text-navy-400" />
          <span className="flex-1 text-[13.5px] font-medium text-navy-800">How alerts are generated — {rules.data?.length ?? '…'} prototype screening rules available to your role</span>
          <Badge tone="amber">Prototype heuristics · not validated clinical thresholds</Badge>
          <ChevronDown className={cx('h-4 w-4 text-navy-400 transition-transform', showRules && 'rotate-180')} />
        </button>
        {showRules && rules.data && (
          <div className="grid grid-cols-1 gap-3 border-t border-line p-5 lg:grid-cols-2">
            {rules.data.map((r) => (
              <div key={r.id} className="rounded-xl border border-line bg-canvas p-4">
                <div className="flex items-center justify-between gap-2">
                  <span className="text-[14px] font-semibold text-navy-900">{r.name}</span>
                  <span className="font-mono text-[11px] text-navy-400">{r.id} v{r.version}</span>
                </div>
                <p className="mt-1 text-[13px] text-navy-600">{r.description}</p>
                <ul className="mt-2 list-disc space-y-0.5 pl-5 text-[12.5px] text-navy-600">{r.parameters.map((p) => <li key={p}>{p}</li>)}</ul>
                <div className="mt-2 text-[12px] text-navy-500">Routes to: <span className="font-medium text-navy-700">{r.routesTo}</span></div>
              </div>
            ))}
          </div>
        )}
      </Card>

      <Card className="mb-4" padded={false}>
        <div className="flex flex-wrap items-center gap-2 p-3">
          <div className="relative min-w-[220px] flex-1">
            <Search className="pointer-events-none absolute left-3 top-1/2 h-4 w-4 -translate-y-1/2 text-navy-400" />
            <input value={text} onChange={(e) => setText(e.target.value)} placeholder="Search alert titles, reasons or patient names"
              aria-label="Search clinical alerts"
              className="h-9 w-full rounded-lg border border-line bg-white pl-9 pr-3 text-sm focus:border-coral-300 focus:outline-none focus:ring-2 focus:ring-coral-100" />
          </div>
          <FilterSelect label="Category" value={params.get('category') ?? ''} onChange={(v) => setParam('category', v)}
            options={Object.entries(facets.data?.categories ?? {}).map(([id, label]) => [id, label])} />
          <FilterSelect label="Review status" value={params.get('status') ?? ''} onChange={(v) => setParam('status', v)}
            options={(facets.data?.statuses ?? []).map((s) => [s, FLAG_STATUS_LABEL[s] ?? titleCase(s)])} />
          <FilterSelect label="Priority" value={params.get('priority') ?? ''} onChange={(v) => setParam('priority', v)}
            options={(facets.data?.priorities ?? []).map((p) => [p, p === 'EXPEDITED' ? 'Expedited review' : 'Standard review'])} />
          <FilterSelect label="Specialty" value={params.get('specialty') ?? ''} onChange={(v) => setParam('specialty', v)}
            options={(facets.data?.specialties ?? []).map((s) => [s, s])} />
          {active.length > 0 && (
            <Button size="sm" variant="ghost" onClick={() => { setText(''); setParams(group === 'OPEN' ? {} : { statusGroup: group }, { replace: true }) }}>
              <X className="h-3.5 w-3.5" />Clear filters
            </Button>
          )}
        </div>
      </Card>

      <div className="mb-4 flex flex-wrap items-end justify-between gap-3">
        <Tabs<Group> value={group} onChange={(g) => setParam('statusGroup', g === 'OPEN' ? '' : g)} tabs={[
          { id: 'OPEN', label: 'Unresolved' },
          { id: 'CLOSED', label: 'Resolved / dismissed' },
          { id: 'ANY', label: 'All' },
        ]} />
        {data && (
          <span className={cx('text-[12.5px] text-navy-500', isFetching && 'opacity-60')}>
            {data.totalFlags} alert{data.totalFlags === 1 ? '' : 's'} · {data.totalPatients} patient{data.totalPatients === 1 ? '' : 's'}
          </span>
        )}
      </div>

      {data?.notice && <div className="mb-3 rounded-lg border border-amber-200 bg-amber-50 px-3 py-2 text-[12.5px] text-amber-800">{data.notice}</div>}
      {data?.warnings.map((w) => <div key={w} className="mb-2 text-[12px] text-navy-500">{w}</div>)}
      {isLoading && <Loading />}
      {error && <ErrorBox error={error} />}
      {data && data.results.length === 0 && <Card><EmptyState title="No clinical alerts match these filters" /></Card>}
      <div className="space-y-3">
        {data?.results.map((h) => <FlagHitCard key={h.flagId} hit={h} />)}
      </div>
    </div>
  )
}

function FilterSelect({ label, value, onChange, options }: { label: string; value: string; onChange: (v: string) => void; options: string[][] }) {
  return (
    <select value={value} onChange={(e) => onChange(e.target.value)} aria-label={label}
      className={cx('h-9 rounded-lg border bg-white px-3 text-[13px]', value ? 'border-coral-300 text-navy-900' : 'border-line text-navy-600')}>
      <option value="">{label}: any</option>
      {options.map(([v, l]) => <option key={v} value={v}>{l}</option>)}
    </select>
  )
}
