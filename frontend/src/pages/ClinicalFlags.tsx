import { ChevronDown, Info, PlayCircle } from 'lucide-react'
import { useMemo, useState } from 'react'
import { Link } from 'react-router-dom'
import { useFlags, useRules, useRunAnalysis } from '../api/hooks'
import { FlagStatusBadge, PriorityBadge } from '../components/status'
import { Badge, Button, Card, EmptyState, ErrorBox, Loading, PageHeader, Tabs } from '../components/ui'
import { RULE_LABEL, cx, fmtDate, relative } from '../lib/format'
import { useApp } from '../state/AppContext'

type View = 'open' | 'all' | 'REVIEWED' | 'DISMISSED'

export default function ClinicalFlags() {
  const { data, isLoading, error } = useFlags()
  const rules = useRules()
  const run = useRunAnalysis()
  const { toast } = useApp()
  const [view, setView] = useState<View>('open')
  const [rule, setRule] = useState('')
  const [showRules, setShowRules] = useState(false)

  const flags = useMemo(() => (data ?? [])
    .filter((f) => view === 'all' || (view === 'open' ? ['UNREVIEWED', 'IN_REVIEW'].includes(f.status) : f.status === view))
    .filter((f) => !rule || f.ruleId === rule)
    .sort((a, b) => (a.reviewPriority === b.reviewPriority ? b.updatedAt.localeCompare(a.updatedAt) : a.reviewPriority === 'EXPEDITED' ? -1 : 1)),
  [data, view, rule])
  const count = (v: View) => (data ?? []).filter((f) => v === 'all' || (v === 'open' ? ['UNREVIEWED', 'IN_REVIEW'].includes(f.status) : f.status === v)).length

  return (
    <div>
      <PageHeader eyebrow="Feature B" title="Clinical Flags"
        subtitle="Candidate review items generated by explainable, deterministic screening rules. Each flag cites the exact source records that triggered it."
        actions={<Button variant="navy" loading={run.isPending} onClick={() => run.mutate(undefined, {
          onSuccess: (r) => toast({ tone: 'success', title: 'Screening run complete', body: `${r.flagsCreated} new · ${r.flagsUpdated} updated · ${r.flagsUnchanged} unchanged — duplicate flags are never created.` }),
          onError: (e) => toast({ tone: 'error', title: 'Screening failed', body: (e as Error).message }),
        })}><PlayCircle className="h-4 w-4" />Run screening</Button>} />

      <Card className="mb-5" padded={false}>
        <button onClick={() => setShowRules((s) => !s)} className="flex w-full items-center gap-2 px-5 py-3 text-left">
          <Info className="h-4 w-4 text-navy-400" />
          <span className="flex-1 text-[13.5px] font-medium text-navy-800">How flags are generated — {rules.data?.length ?? 4} prototype screening rules</span>
          <Badge tone="amber">Prototype heuristics · not validated clinical thresholds</Badge>
          <ChevronDown className={cx('h-4 w-4 text-navy-400 transition-transform', showRules && 'rotate-180')} />
        </button>
        {showRules && rules.data && (
          <div className="grid grid-cols-1 gap-3 border-t border-line p-5 lg:grid-cols-2">
            {rules.data.map((r) => (
              <div key={r.id} className="rounded-xl border border-line bg-canvas p-4">
                <div className="flex items-center justify-between gap-2">
                  <span className="text-[14px] font-semibold text-navy-900">{r.name}</span>
                  <span className="font-mono text-[11px] text-navy-400">{r.id} v{r.version}</span>
                </div>
                <p className="mt-1 text-[13px] text-navy-600">{r.description}</p>
                <ul className="mt-2 list-disc space-y-0.5 pl-5 text-[12.5px] text-navy-600">{r.parameters.map((p) => <li key={p}>{p}</li>)}</ul>
                <div className="mt-2 text-[12px] text-navy-500">Routes to: <span className="font-medium text-navy-700">{r.routesTo}</span></div>
              </div>
            ))}
          </div>
        )}
      </Card>

      <div className="mb-4 flex flex-wrap items-end justify-between gap-3">
        <Tabs<View> value={view} onChange={setView} tabs={[
          { id: 'open', label: 'Open', count: count('open') },
          { id: 'REVIEWED', label: 'Reviewed', count: count('REVIEWED') },
          { id: 'DISMISSED', label: 'Dismissed', count: count('DISMISSED') },
          { id: 'all', label: 'All', count: count('all') },
        ]} />
        <select value={rule} onChange={(e) => setRule(e.target.value)} className="h-9 rounded-lg border border-line bg-white px-3 text-[13px] text-navy-700">
          <option value="">All rules</option>
          {Object.entries(RULE_LABEL).map(([id, l]) => <option key={id} value={id}>{l}</option>)}
        </select>
      </div>

      {isLoading && <Loading />}
      {error && <ErrorBox error={error} />}
      {data && flags.length === 0 && <Card><EmptyState title="No flags in this view" /></Card>}
      <div className="space-y-3">
        {flags.map((f) => (
          <Link key={f.flagId} to={`/flags/${f.flagId}`} className="block rounded-xl border border-line bg-white p-4 transition-shadow hover:border-coral-200 hover:shadow-md">
            <div className="flex flex-wrap items-start justify-between gap-3">
              <div className="min-w-0 flex-1">
                <div className="flex flex-wrap items-center gap-2">
                  <span className="text-[15px] font-semibold text-navy-900">{f.title}</span>
                  <Badge>{RULE_LABEL[f.ruleId] ?? f.ruleId}</Badge>
                  {f.alertId && <Badge tone="coral">Routed to Anesthesia OB</Badge>}
                  {f.evidenceUpdatedAt && <Badge tone="amber">New evidence {relative(f.evidenceUpdatedAt)}</Badge>}
                </div>
                <div className="mt-1 text-[13px] text-navy-500"><span className="font-medium text-navy-800">{f.patientName}</span> · {f.patientDisplayId} · created {fmtDate(f.createdAt)}</div>
                <p className="mt-2 line-clamp-2 text-[13.5px] leading-relaxed text-navy-700">{f.detectionReason}</p>
                <div className="mt-2 flex flex-wrap gap-1.5 text-[12px] text-navy-500">
                  <span>{f.evidence.filter((e) => e.role === 'TRIGGER').length} triggering findings</span>·
                  <span>{f.evidence.length} evidence records</span>·
                  <span>{Array.from(new Set(f.evidence.map((e) => e.record?.orgName).filter(Boolean))).length} organizations</span>
                </div>
              </div>
              <div className="flex shrink-0 flex-col items-end gap-1.5">
                <FlagStatusBadge status={f.status} />
                <PriorityBadge priority={f.reviewPriority} />
                <span className="text-[11.5px] text-navy-400">updated {relative(f.updatedAt)}</span>
              </div>
            </div>
          </Link>
        ))}
      </div>
    </div>
  )
}
